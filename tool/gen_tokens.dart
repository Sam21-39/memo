// Generates lib/core/theme/tokens.dart from design/tokens.json, the copy of
// the Memō Design System's project/tokens.json.
//
//   fvm dart run tool/gen_tokens.dart          write the file
//   fvm dart run tool/gen_tokens.dart --check  exit 1 if the file is stale (CI)
//
// Colour values in tokens.json are #RRGGBB or #AARRGGBB (alpha first, as the
// design system's usage notes describe: ink-70 dark is #b3f2f0ec = 70 %).
import 'dart:convert';
import 'dart:io';

const _source = 'design/tokens.json';
const _target = 'lib/core/theme/tokens.dart';

void main(List<String> args) {
  final json =
      jsonDecode(File(_source).readAsStringSync()) as Map<String, dynamic>;
  final out = _format(generate(json));
  final file = File(_target);
  if (args.contains('--check')) {
    if (!file.existsSync() || file.readAsStringSync() != out) {
      stderr.writeln(
        '$_target is stale: run fvm dart run tool/gen_tokens.dart',
      );
      exit(1);
    }
    return;
  }
  file.writeAsStringSync(out);
  stdout.writeln('wrote $_target');
}

/// Formats with the SDK running this script, so --check and the committed
/// file always agree.
String _format(String source) {
  final tmp = File(
    '${Directory.systemTemp.createTempSync('tokens').path}/t.dart',
  )..writeAsStringSync(source);
  final result = Process.runSync(Platform.resolvedExecutable, [
    'format',
    tmp.path,
  ]);
  if (result.exitCode != 0) throw StateError('${result.stderr}');
  final formatted = tmp.readAsStringSync();
  tmp.parent.deleteSync(recursive: true);
  return formatted;
}

String generate(Map<String, dynamic> json) {
  final b = StringBuffer()
    ..writeln(
      '// GENERATED by tool/gen_tokens.dart from $_source. Do not edit.',
    )
    ..writeln('// ignore_for_file: constant_identifier_names')
    ..writeln()
    ..writeln("import 'package:flutter/material.dart';")
    ..writeln();

  _colors(b, json['color'] as Map<String, dynamic>);
  _type(b, json['type'] as Map<String, dynamic>);
  _lengths(b, 'MemoSpace', json['spacing'] as Map<String, dynamic>);
  _lengths(b, 'MemoRadius', json['radius'] as Map<String, dynamic>);
  _lengths(b, 'MemoGlass', json['blur'] as Map<String, dynamic>);
  b.write(_fixed);
  return b.toString();
}

String _camel(String name) {
  final parts = name.split(RegExp('[-_.]'));
  final head = parts.first;
  final tail = parts.skip(1).map((p) => p[0].toUpperCase() + p.substring(1));
  final id = head + tail.join();
  // Strip the family prefix: radius-card -> card, space-4 -> space4.
  return id;
}

String _color(String hex) {
  final h = hex.replaceFirst('#', '').toUpperCase();
  final argb = switch (h.length) {
    6 => 'FF$h',
    8 => h,
    _ => throw FormatException('bad colour $hex'),
  };
  return 'Color(0x$argb)';
}

void _colors(StringBuffer b, Map<String, dynamic> color) {
  final tokens = (color['tokens'] as List).cast<Map<String, dynamic>>();
  final names = [for (final t in tokens) _camel(t['name'] as String)];

  b
    ..writeln('/// Colour tokens. Read with `MemoColors.of(context)`.')
    ..writeln('@immutable')
    ..writeln('class MemoColors extends ThemeExtension<MemoColors> {')
    ..writeln('  const MemoColors({')
    ..writeln([for (final n in names) '    required this.$n,'].join('\n'))
    ..writeln('  });')
    ..writeln();
  for (var i = 0; i < tokens.length; i++) {
    b
      ..writeln('  /// ${tokens[i]['usage']}')
      ..writeln('  final Color ${names[i]};');
  }
  for (final theme in ['light', 'dark']) {
    b
      ..writeln()
      ..writeln('  static const $theme = MemoColors(');
    for (var i = 0; i < tokens.length; i++) {
      final value = tokens[i]['value'];
      final hex = value is String
          ? value
          : (value as Map)[theme] ?? value['light'];
      b.writeln('    ${names[i]}: ${_color(hex as String)},');
    }
    b.writeln('  );');
  }
  b
    ..writeln()
    ..writeln('  static MemoColors of(BuildContext context) =>')
    ..writeln('      Theme.of(context).extension<MemoColors>()!;')
    ..writeln()
    ..writeln('  @override')
    ..writeln('  MemoColors copyWith() => this;')
    ..writeln()
    ..writeln('  @override')
    ..writeln('  MemoColors lerp(MemoColors? other, double t) {')
    ..writeln('    if (other == null) return this;')
    ..writeln('    return MemoColors(')
    ..writeln(
      [
        for (final n in names) '      $n: Color.lerp($n, other.$n, t)!,',
      ].join('\n'),
    )
    ..writeln('    );')
    ..writeln('  }')
    ..writeln('}')
    ..writeln();
}

double _px(Object v) => v is num
    ? v.toDouble()
    : double.parse((v as String).replaceAll(RegExp('px|rem|em'), ''));

String _num(double v) => v == v.roundToDouble() ? '${v.toInt()}.0' : '$v';

void _type(StringBuffer b, Map<String, dynamic> type) {
  b
    ..writeln('/// Type tokens. Sans for what a person reads, mono for what a')
    ..writeln(
      '/// clock produces. Colour is applied by the theme or the caller.',
    )
    ..writeln('abstract final class MemoType {')
    ..writeln("  static const sans = 'Instrument Sans';")
    ..writeln("  static const mono = 'IBM Plex Mono';")
    ..writeln('  static const _tabular = [FontFeature.tabularFigures()];');
  for (final group in (type['groups'] as List).cast<Map<String, dynamic>>()) {
    final family = group['family'] == 'mono' ? 'mono' : 'sans';
    for (final s in (group['styles'] as List).cast<Map<String, dynamic>>()) {
      final size = _px(s['fontSize'] as Object);
      final line = _px(s['lineHeight'] as Object);
      final weight = s['fontWeight'];
      final spacing = s['letterSpacing'];
      final name = _camel(s['name'] as String);
      final tabular =
          family == 'mono' && (name == 'clock' || name == 'labelMedium');
      b
        ..writeln()
        ..writeln('  /// ${s['usage']}')
        ..writeln('  static const $name = TextStyle(')
        ..writeln('    fontFamily: $family,')
        ..writeln('    fontSize: ${_num(size)},')
        ..writeln('    height: ${line / size},')
        ..writeln('    fontWeight: FontWeight.w$weight,');
      if (spacing != null) {
        b.writeln('    letterSpacing: ${_num(_px(spacing as Object))},');
      }
      if (tabular) b.writeln('    fontFeatures: _tabular,');
      b.writeln('  );');
    }
  }
  b
    ..writeln('}')
    ..writeln();
}

void _lengths(StringBuffer b, String cls, Map<String, dynamic> family) {
  final note = family['note'];
  if (note != null) b.writeln('/// $note');
  b.writeln('abstract final class $cls {');
  for (final t in (family['tokens'] as List).cast<Map<String, dynamic>>()) {
    var name = _camel(t['name'] as String);
    // radius-card -> card; blur-chrome stays (it is not a prefix of the class).
    if (cls == 'MemoRadius' && name.startsWith('radius')) {
      name = name[6].toLowerCase() + name.substring(7);
    }
    b
      ..writeln('  /// ${t['usage']}')
      ..writeln('  static const $name = ${_num(_px(t['value'] as Object))};');
  }
  b
    ..writeln('}')
    ..writeln();
}

/// Values the design system states in its README rather than tokens.json
/// (motion), or that it draws but does not name (tag dots). Kept here so no
/// literal lives outside tokens.dart.
const _fixed = '''
/// Motion from the design system README: ease-out cubic, nothing bounces.
abstract final class MemoMotion {
  static const fast = Duration(milliseconds: 120);
  static const base = Duration(milliseconds: 200);
  static const slow = Duration(milliseconds: 320);
  static const curve = Curves.easeOutCubic;
}

/// Tag dot colours, as drawn on the Memō Screens canvas. A tag's colour is
/// picked from its name, so the list order is part of the contract.
abstract final class MemoTagPalette {
  static const colors = [
    Color(0xFFFF5A5F),
    Color(0xFF3F9E6B),
    Color(0xFF5C8FD9),
    Color(0xFFC9A15F),
    Color(0xFF8A6F84),
  ];
}
''';
